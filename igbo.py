
# Igbo and English Translation Dictionary

translations = {
    "Daalụ": "Thank you",
    "Anọ m ebe a": "I am here",
    "Chukwu": "God",
    "Anụmanụ": "Animal",
    "Bịa": "Come"
}

print("IGBO LANGUAGE          ENGLISH")
print("--------------------------------")

for igbo, english in translations.items():
    print(f"{igbo:<22} {english}")
